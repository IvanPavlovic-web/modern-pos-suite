class Command(BaseCommand):
    help = 'Kreira role grupe, korisnike i demo proizvode za market.'

    def add_arguments(self, parser):
        parser.add_argument(
            '--reset',
            action='store_true',
            help='Obriši sve postojeće proizvode i korisnike prije seed-a',
        )

    def handle(self, *args, **options):
        reset = options.get('reset', False)

        if reset:
            self.stdout.write(self.style.WARNING('Brišem postojeće podatke...'))
            Product.objects.all().delete()
            Category.objects.all().delete()
            User.objects.filter(is_superuser=False).delete()

        # GRUPE
        for gname in ['cashier', 'manager', 'admin']:
            Group.objects.get_or_create(name=gname)
        self.stdout.write(self.style.SUCCESS('✓ Grupe: cashier, manager, admin'))

        # KORISNICI
        created_users = 0
        updated_users = 0
        for username, password, group, first_name, last_name, is_staff, is_super in USERS:
            user, created = User.objects.get_or_create(username=username)
            user.first_name = first_name
            user.last_name = last_name
            user.is_staff = is_staff
            user.is_superuser = is_super
            user.set_password(password)
            user.save()
            user.groups.clear()
            user.groups.add(Group.objects.get(name=group))
            if created:
                created_users += 1
            else:
                updated_users += 1

        self.stdout.write(self.style.SUCCESS(
            f'✓ Korisnici: {created_users} novih, {updated_users} ažuriranih'
        ))

        # KATEGORIJE
        cat_objs = {}
        for name in CATEGORIES:
            c, _ = Category.objects.get_or_create(name=name)
            cat_objs[name] = c
        self.stdout.write(self.style.SUCCESS(f'✓ Kategorije: {len(cat_objs)}'))

        # PROIZVODI
        created_products = 0
        updated_products = 0
        for name, barcode, cat, price, stock, tax in PRODUCTS:
            product, created = Product.objects.update_or_create(
                barcode=barcode,
                defaults={
                    'name': name,
                    'category': cat_objs.get(cat),
                    'price': Decimal(str(price)),
                    'stock': stock,
                    'tax_rate': Decimal(str(tax)),
                    'active': True,
                },
            )
            if created:
                created_products += 1
            else:
                updated_products += 1

        self.stdout.write(self.style.SUCCESS(
            f'✓ Proizvodi: {created_products} novih, {updated_products} ažuriranih'
        ))

        self.stdout.write('')
        self.stdout.write(self.style.SUCCESS('═' * 60))
        self.stdout.write(self.style.SUCCESS('  SEED ZAVRŠEN'))
        self.stdout.write(self.style.SUCCESS('═' * 60))
        self.stdout.write('')
        self.stdout.write('  KORISNICI:')
        self.stdout.write('  ┌─────────────────────────────────────────────────┐')
        self.stdout.write('  │  ADMIN:    admin / admin123                     │')
        self.stdout.write('  │            admin2 / admin123                    │')
        self.stdout.write('  │  MANAGER:  manager / manager123                 │')
        self.stdout.write('  │            manager2 / manager123                │')
        self.stdout.write('  │            manager3 / manager123                │')
        self.stdout.write('  │  KASIRI:   cashier1..8 / cashier123             │')
        self.stdout.write('  └─────────────────────────────────────────────────┘')
        self.stdout.write('')
        self.stdout.write(f'  UKUPNO PROIZVODA: {Product.objects.count()}')
        self.stdout.write(f'  UKUPNO KATEGORIJA: {Category.objects.count()}')
        self.stdout.write(f'  UKUPNO KORISNIKA: {User.objects.count()}')
        self.stdout.write('')
        self.stdout.write(self.style.SUCCESS('═' * 60))